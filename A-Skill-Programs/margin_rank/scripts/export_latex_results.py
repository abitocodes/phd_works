def _wrap_table(caption: str, label: str, tabular_body: str) -> str:
    """Emit a table that never exceeds \\linewidth."""
    return f"""\\begin{{table}}[htbp]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\fitwidth{{%
{tabular_body}
}}
\\end{{table}}
"""

